const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const storage=new Map();
const context={window:{},localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)}};
vm.createContext(context);
for(const file of ['data/definitions.js','core/engine.js','campaign/progress.js','core/ai.js']) vm.runInContext(fs.readFileSync(path.join(root,'js',file),'utf8'),context);
const P=context.window.CampaignProgress, G=context.window.TacticsGame;
const p=P.load();
assert.deepEqual([...p.owned],['treent_ancient']);
assert.equal(p.level,1);assert.equal(p.gold,0);
assert.equal(P.opponents(1).length,1);assert.equal(P.opponents(3).length,2);
assert.equal(P.opponents(4).length,3);assert.equal(P.opponents(5).length,4);
for(let level=1;level<=12;level++){
  const enemyIds=P.opponents(level);
  assert.ok(enemyIds.every(id=>context.window.GAME_DATA.cards[id]),`Missing stage ${level} enemy`);
  const stage=new G();stage.startCampaign(['treent_ancient'],enemyIds,level);
  assert.equal(stage.units.filter(u=>u.team==='B').length,enemyIds.length);
  const lineup=['treent_ancient','knight','ranger','mage'].slice(0,P.partySize(level));
  const simulation=new G();assert.equal(P.start(simulation,lineup,level),true);
  lineup.forEach((id,i)=>simulation.deploy(id,{x:i,y:0}));
  for(let step=0;step<400&&simulation.phase==='battle';step++)context.window.TacticsAI.step(simulation,simulation.team);
  assert.equal(simulation.phase,'end',`Stage ${level} became stuck`);
}
const g=new G();g.startCampaign(['treent_ancient'],P.opponents(1),1);
assert.equal(g.phase,'deploy');assert.equal(g.units.filter(u=>u.team==='B').length,1);
assert.equal(g.deploy('treent_ancient',{x:1,y:0}),true);
assert.equal(g.phase,'battle');
assert.equal(P.completeLevel(p,1),true);assert.equal(p.gold,10);
assert.equal(P.completeLevel(p,1),false);
const newCard=P.available(p)[0];assert.equal(P.chooseReward(p,newCard),true);
assert.equal(p.level,2);assert.ok(p.owned.includes(newCard));
assert.equal(P.buy(p,P.available(p)[0]),false);
p.gold=30;P.save(p);const buyId=P.available(p)[0];assert.equal(P.buy(p,buyId),true);
assert.equal(p.gold,0);assert.ok(P.load().owned.includes(buyId));
p.gold=30;const skillId=P.availableSkills(p)[0];assert.equal(P.buy(p,skillId),true);
assert.ok(p.ownedSkills.includes(skillId));assert.equal(P.buy(p,skillId),false);
for(const id of P.available(p).slice(0,7)) p.owned.push(id);
assert.ok(p.owned.length>=10);
assert.equal(P.onlineWin(p,'match-1'),true);assert.equal(P.onlineWin(p,'match-1'),false);
const ai=new G();ai.startCampaign(['treent_ancient'],['skeleton'],1);
ai.deploy('treent_ancient',{x:1,y:0});ai.endTurn();
for(let i=0;i<20&&ai.team==='B'&&ai.phase==='battle';i++) context.window.TacticsAI.step(ai);
assert.ok(ai.team==='A'||ai.phase==='end');
console.log('Progression and AI tests passed');
